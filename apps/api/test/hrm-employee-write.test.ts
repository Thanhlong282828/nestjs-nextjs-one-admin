import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { PrismaMariaDb } from '@prisma/adapter-mariadb';
import { CreateScopedEmployeeCommand, CreateScopedEmployeeHandler, UpdateScopedEmployeeCommand, UpdateScopedEmployeeHandler, ChangeScopedEmployeeStatusCommand, ChangeScopedEmployeeStatusHandler } from '@aurum/hrm';
import { PrismaClient } from '../src/generated/prisma/client';
import { EmployeeWriteDeniedError, EmployeeWriteInvalidError, PrismaScopedEmployeeWriter } from '../src/hrm/prisma-scoped-employee.writer';

test('scoped employee writes persist and audit only in the isolated MySQL test database', async () => {
  const raw = process.env.MYSQL_MIGRATION_TEST_DATABASE_URL;
  if (!raw) throw new Error('MYSQL_MIGRATION_TEST_DATABASE_URL is required');
  const url = new URL(raw);
  if (url.protocol !== 'mysql:' || url.hostname !== '127.0.0.1' || !['3306', '3307'].includes(url.port) || url.pathname !== '/aurum_nestjs_test' || url.search || url.hash) throw new Error('Refusing non-test database');
  const db = new PrismaClient({ adapter: new PrismaMariaDb(raw) });
  const companyId = randomUUID(), branchId = randomUUID(), departmentId = randomUUID(), userId = randomUUID(), sessionId = randomUUID();
  try {
    const target = await db.$queryRaw<Array<{ db: string }>>`SELECT DATABASE() AS db`;
    assert.equal(target[0]?.db, 'aurum_nestjs_test');
    await db.company.create({ data: { id: companyId, name: 'Test scope' } });
    await db.branch.create({ data: { id: branchId, companyId, name: 'Test branch' } });
    await db.tenantClassification.create({ data: { companyId, classification: 'DEMO', provenance: 'isolated-test' } });
    await db.classifiedBranchScope.create({ data: { companyId, branchId, classification: 'DEMO' } });
    await db.department.create({ data: { id: departmentId, companyId, branchId, code: 'TEST', name: 'Test department' } });
    await db.identityUser.create({ data: { id: userId, email: `${userId}@example.invalid`, passwordHash: 'test-only' } });
    await db.companyMembership.create({ data: { userId, companyId } });
    await db.branchGrant.create({ data: { userId, companyId, branchId } });
    await db.membershipPermission.createMany({ data: ['employee.create', 'employee.update', 'employee.change-status', 'tenant.demo.read'].map(permission => ({ userId, companyId, permission })) });
    await db.userSession.create({ data: { id: sessionId, userId, tokenHash: randomUUID().replaceAll('-', '').padEnd(64, '0'), expiresAt: new Date(Date.now() + 60_000) } });
    const actor = { userId, sessionId }, input = { companyId, branchId, departmentId, code: 'TEST-1', fullName: 'Test User' };
    const writer = new PrismaScopedEmployeeWriter(db);
    const created = await new CreateScopedEmployeeHandler(writer).execute(new CreateScopedEmployeeCommand(actor, input));
    assert.equal((await db.employee.findUnique({ where: { id: created.id } }))?.fullName, input.fullName);
    await assert.rejects(new CreateScopedEmployeeHandler(writer).execute(new CreateScopedEmployeeCommand(actor, input)));
    await assert.rejects(new CreateScopedEmployeeHandler(writer).execute(new CreateScopedEmployeeCommand(actor, { ...input, code: 'TEST-2', departmentId: randomUUID() })), EmployeeWriteInvalidError);
    await assert.rejects(new UpdateScopedEmployeeHandler(writer).execute(new UpdateScopedEmployeeCommand(actor, randomUUID(), input)), EmployeeWriteDeniedError);
    await new UpdateScopedEmployeeHandler(writer).execute(new UpdateScopedEmployeeCommand(actor, created.id, { ...input, fullName: 'Changed' }));
    await new ChangeScopedEmployeeStatusHandler(writer).execute(new ChangeScopedEmployeeStatusCommand(actor, created.id, companyId, branchId, 'inactive'));
    assert.equal((await db.employee.findUnique({ where: { id: created.id } }))?.status, 'inactive');
    assert.deepEqual((await db.hrmEmployeeAudit.findMany({ where: { employeeId: created.id }, orderBy: { occurredAt: 'asc' } })).map(row => row.action).sort(), ['create', 'status', 'update']);
    const failingDb = db.$extends({ query: { hrmEmployeeAudit: { create() { throw new Error('AUDIT_UNAVAILABLE'); } } } }) as unknown as PrismaClient;
    const failingWriter = new PrismaScopedEmployeeWriter(failingDb);
    await assert.rejects(new CreateScopedEmployeeHandler(failingWriter).execute(new CreateScopedEmployeeCommand(actor, { ...input, code: 'ROLLBACK' })), /AUDIT_UNAVAILABLE/);
    assert.equal(await db.employee.count({ where: { companyId, code: 'ROLLBACK' } }), 0);
    await assert.rejects(new UpdateScopedEmployeeHandler(failingWriter).execute(new UpdateScopedEmployeeCommand(actor, created.id, { ...input, fullName: 'Must roll back' })), /AUDIT_UNAVAILABLE/);
    assert.equal((await db.employee.findUnique({ where: { id: created.id } }))?.fullName, 'Changed');
    await assert.rejects(new CreateScopedEmployeeHandler(writer).execute(new CreateScopedEmployeeCommand(actor, { ...input, companyId: randomUUID() })), EmployeeWriteDeniedError);
    await assert.rejects(new CreateScopedEmployeeHandler(writer).execute(new CreateScopedEmployeeCommand(actor, { ...input, branchId: randomUUID() })), EmployeeWriteDeniedError);
    const concurrent = await Promise.allSettled([1, 2].map(() => new CreateScopedEmployeeHandler(writer).execute(new CreateScopedEmployeeCommand(actor, { ...input, code: 'RACE' }))));
    assert.equal(concurrent.filter(result => result.status === 'fulfilled').length, 1);
    assert.equal(await db.employee.count({ where: { companyId, code: 'RACE' } }), 1);
    await db.membershipPermission.delete({ where: { companyId_userId_permission: { companyId, userId, permission: 'employee.create' } } });
    await assert.rejects(new CreateScopedEmployeeHandler(writer).execute(new CreateScopedEmployeeCommand(actor, { ...input, code: 'NO-PERMISSION' })), EmployeeWriteDeniedError);
    await db.branchGrant.delete({ where: { companyId_userId_branchId: { companyId, userId, branchId } } });
    await assert.rejects(new UpdateScopedEmployeeHandler(writer).execute(new UpdateScopedEmployeeCommand(actor, created.id, input)), EmployeeWriteDeniedError);
  } finally {
    await db.hrmEmployeeAudit.deleteMany({ where: { companyId } });
    await db.employee.deleteMany({ where: { companyId } });
    await db.userSession.deleteMany({ where: { userId } });
    await db.membershipPermission.deleteMany({ where: { companyId, userId } });
    await db.branchGrant.deleteMany({ where: { companyId, userId } });
    await db.companyMembership.deleteMany({ where: { companyId, userId } });
    await db.identityUser.deleteMany({ where: { id: userId } });
    await db.department.deleteMany({ where: { companyId } });
    await db.classifiedBranchScope.deleteMany({ where: { companyId, branchId } });
    await db.tenantClassification.deleteMany({ where: { companyId } });
    await db.branch.deleteMany({ where: { companyId } });
    await db.company.deleteMany({ where: { id: companyId } });
    await db.$disconnect();
  }
});
