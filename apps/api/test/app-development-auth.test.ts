test('development auth refuses production, missing config and nonlocal targets', () => {
  const { DevelopmentAuthModule } = require('../dist/identity/http/development-auth.module.js') as typeof import('../src/identity/http/development-auth.module');
  const local = { NODE_ENV: 'development', DATABASE_URL: 'mysql://user:password@127.0.0.1:3306/aurum_nestjs', AURUM_AUTH_ORIGINS: 'http://localhost:3000', AURUM_AUTH_DUMMY_HASH: '$argon2id$test' };
  assert.throws(() => DevelopmentAuthModule.fromEnvironment({ ...local, NODE_ENV: 'production' }));
  assert.throws(() => DevelopmentAuthModule.fromEnvironment({ ...local, DATABASE_URL: 'mysql://user:password@127.0.0.1:3306/laravel' }));
  assert.throws(() => DevelopmentAuthModule.fromEnvironment({ ...local, DATABASE_URL: 'mysql://user:password@remote.example:3306/aurum_nestjs' }));
  assert.throws(() => DevelopmentAuthModule.fromEnvironment({ ...local, AURUM_AUTH_ORIGINS: 'https://remote.example' }));
  assert.throws(() => DevelopmentAuthModule.fromEnvironment({ ...local, AURUM_AUTH_DUMMY_HASH: '' }));
});
